-- ========================================================
-- TÂY NGUYÊN UNIVERSITY (TNU) - UNIFIED CHARACTER OUTFIT SQL SCHEMA
-- Quản lý khung hình (Frames) và hoạt ảnh 4 Bộ Trang Phục Hoàn Chỉnh Đồng Bộ 100%
-- ========================================================

CREATE TABLE IF NOT EXISTS body_templates (
    body_id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    desc_key VARCHAR(100) NOT NULL,
    icon_url VARCHAR(255) NOT NULL,
    body_type VARCHAR(50) DEFAULT 'full_outfit_directional',
    total_frames INT NOT NULL DEFAULT 12,
    walk_cycle_length INT NOT NULL DEFAULT 4,
    render_width INT NOT NULL,
    render_height INT NOT NULL,
    rarity VARCHAR(20) DEFAULT 'mythic',
    speed_bonus DECIMAL(3,2) DEFAULT 0.70
);

CREATE TABLE IF NOT EXISTS body_frames (
    id INT AUTO_INCREMENT PRIMARY KEY,
    body_id VARCHAR(50) NOT NULL,
    direction VARCHAR(10) NOT NULL,
    action_type VARCHAR(10) NOT NULL,
    frame_index INT NOT NULL DEFAULT 0,
    image_url VARCHAR(255) NOT NULL,
    dx INT DEFAULT 0,
    dy INT DEFAULT 0,
    render_width INT NOT NULL,
    render_height INT NOT NULL,
    flip_x BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (body_id) REFERENCES body_templates(body_id)
);

CREATE TABLE IF NOT EXISTS outfit_heads (
    id INT AUTO_INCREMENT PRIMARY KEY,
    outfit_id VARCHAR(50) NOT NULL,
    direction VARCHAR(10) NOT NULL,
    image_url VARCHAR(255) NOT NULL,
    back_image_url VARCHAR(255) DEFAULT NULL,
    dx INT DEFAULT 0,
    dy INT DEFAULT 0,
    render_width INT NOT NULL,
    render_height INT NOT NULL,
    flip_x BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (outfit_id) REFERENCES body_templates(body_id)
);

