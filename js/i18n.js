class I18nManager {
    constructor() {
        this.currentLocale = localStorage.getItem('tnu_game_locale') || 'vi';
        this.listeners = [];
    }

    getLocale() {
        return this.currentLocale;
    }

    setLocale(locale) {
        if (I18N_DICTIONARY[locale] && this.currentLocale !== locale) {
            this.currentLocale = locale;
            localStorage.setItem('tnu_game_locale', locale);
            this.notify();
        }
    }

    toggleLocale() {
        this.setLocale(this.currentLocale === 'vi' ? 'en' : 'vi');
    }

    t(key, params = {}) {
        const dict = I18N_DICTIONARY[this.currentLocale] || I18N_DICTIONARY.vi;
        let text = dict[key] || I18N_DICTIONARY.vi[key] || key;
        
        // Thay thế các biến động: {count}, {name}, v.v.
        Object.entries(params).forEach(([k, v]) => {
            text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
        });
        return text;
    }

    subscribe(callback) {
        if (typeof callback === 'function') {
            this.listeners.push(callback);
        }
    }

    notify() {
        this.listeners.forEach(cb => cb(this.currentLocale));
    }
}

window.i18n = new I18nManager();
